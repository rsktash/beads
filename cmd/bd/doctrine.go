// validateAreaName refuses a value the vocabulary does not carry and names
// every value it does, so a writer who guessed wrong picks from a list instead
// of guessing again. An empty value is not validated: it means "unset".
func validateAreaName(cc *cmdCtx, kind, name string) error {
	name = strings.TrimSpace(name)
	if name == "" {
		return nil
	}
	areas, err := cc.store.ListAreas(cc.ctx)
	if err != nil {
		return err
	}
	var known []string
	for _, a := range areas {
		if a.Kind != kind {
			continue
		}
		if a.Name == name {
			return nil
		}
		known = append(known, a.Name)
	}
	return fmt.Errorf("unknown %s %q — the vocabulary is: %s (add one with `bd areas add %s <name>`)",
		kind, name, strings.Join(known, ", "), kind)
}

// concernList splits the comma-separated concern column, dropping empties. A
// ruling that inherited its areas from a bead carries several.
func concernList(s string) []string {
	var out []string
	for _, c := range strings.Split(s, ",") {
		if c = strings.TrimSpace(c); c != "" {
			out = append(out, c)
		}
	}
	return out
}

// doctrineArea is the area column of the listing: the law's concern, its
// workspace when it carries no concern.
func doctrineArea(st beads.Statement) string {
	if st.Concern != "" {
		return st.Concern
	}
	if st.Workspace != "" {
		return st.Workspace
	}
	return "project"
}

// writeDoctrineTable prints one line per law — ruling id, area, law — with the
// first two columns padded so the laws line up under each other.
func writeDoctrineTable(w io.Writer, laws []beads.Statement) {
	if len(laws) == 0 {
		fmt.Fprintln(w, "(no doctrine)")
		return
	}
	idW, areaW := 0, 0
	for _, st := range laws {
		idW = max(idW, utf8.RuneCountInString(st.ID))
		areaW = max(areaW, utf8.RuneCountInString(doctrineArea(st)))
	}
	for _, st := range laws {
		fmt.Fprintf(w, "%s  %s  %s\n",
			padTopicCell(st.ID, idW),
			padTopicCell(doctrineArea(st), areaW),
			headlineText(rulingLineText(st)))
	}
}

// doctrineGroup is one heading of the rendered page and the laws under it.
type doctrineGroup struct {
	name string
	laws []beads.Statement
}

// doctrineGroups buckets the laws under their headings: one per concern in
// vocabulary order (which is the seed order — authority, sync, tokens, schema,
// catalog, frontend, all — with later additions after it), then one per
// workspace, then any area the vocabulary no longer names, alphabetically, so
// a renamed area can never drop a law off the page. A law carrying a concern
// is filed under it, and under every concern it names; only a law with no
// concern at all falls through to its workspace.
func doctrineGroups(areas store.Areas, laws []beads.Statement) []doctrineGroup {
	byConcern := map[string][]beads.Statement{}
	byWorkspace := map[string][]beads.Statement{}
	for _, st := range laws {
		if cs := concernList(st.Concern); len(cs) > 0 {
			for _, c := range cs {
				byConcern[c] = append(byConcern[c], st)
			}
			continue
		}
		if st.Workspace != "" {
			byWorkspace[st.Workspace] = append(byWorkspace[st.Workspace], st)
		}
	}

	var out []doctrineGroup
	drain := func(kind string, m map[string][]beads.Statement) {
		for _, a := range areas {
			if a.Kind != kind {
				continue
			}
			if group, ok := m[a.Name]; ok {
				out = append(out, doctrineGroup{name: a.Name, laws: group})
				delete(m, a.Name)
			}
		}
		leftover := make([]string, 0, len(m))
		for name := range m {
			leftover = append(leftover, name)
		}
		sort.Strings(leftover)
		for _, name := range leftover {
			out = append(out, doctrineGroup{name: name, laws: m[name]})
		}
	}
	drain(store.AreaConcern, byConcern)
	drain(store.AreaWorkspace, byWorkspace)
	return out
}

// writeDoctrinePage renders the whole file: the do-not-edit banner, a title,
// then a heading per area with each law in bold, its rationale under it and an
// attribution line citing the ruling that carries it.
func writeDoctrinePage(w io.Writer, areas store.Areas, laws []beads.Statement) {
	fmt.Fprintln(w, doctrineBanner)
	fmt.Fprintln(w)
	fmt.Fprintln(w, "# Doctrine")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "LEGACY — these laws bind only where no AGENTS.md covers the code. Each is a")
	fmt.Fprintln(w, "project-scoped ruling; no law is added or amended here: a rule goes into the")
	fmt.Fprintln(w, "AGENTS.md of the folder it governs.")

	groups := doctrineGroups(areas, laws)
	if len(groups) == 0 {
		fmt.Fprintln(w)
		fmt.Fprintln(w, "(no doctrine)")
		return
	}
	for _, g := range groups {
		fmt.Fprintln(w)
		fmt.Fprintf(w, "## %s\n", g.name)
		for _, st := range g.laws {
			fmt.Fprintln(w)
			fmt.Fprintf(w, "**%s**\n", singleLine(rulingLineText(st)))
			if r := strings.TrimSpace(st.Rationale); r != "" {
				fmt.Fprintln(w)
				fmt.Fprintln(w, r)
			}
			fmt.Fprintln(w)
			fmt.Fprintln(w, doctrineAttribution(st))
		}
	}
}

// doctrineAttribution is the trailing line under a law: the ruling that
// carries it and the topic it belongs to.
func doctrineAttribution(st beads.Statement) string {
	if topic := strings.TrimSpace(st.Topic); topic != "" {
		return fmt.Sprintf("— %s (%s)", st.ID, topic)
	}
	return "— " + st.ID
}

// singleLine collapses whitespace without truncating: a law is already capped,
// and the bold line must not carry a newline that would break the markdown.
func singleLine(s string) string {
	return strings.Join(strings.Fields(strings.NewReplacer("\r", " ", "\n", " ", "\t", " ").Replace(s)), " ")
}
