// `bd doctrine` reads the project's standing laws. A doctrine is not a new
// record type: it is an active project-scoped ruling carrying an area, a law
// and a rationale. It is legacy: no law is added. docs/doctrine.md is
// generated from that query and never hand-edited.

// doctrineBanner is the first line of the rendered file. It is the only thing
// standing between a generated page and someone editing it by hand.
const doctrineBanner = "<!-- generated by `bd doctrine render` — do not hand-edit -->"

func newDoctrineCmd() *cobra.Command {
	root := &cobra.Command{
		Use:   "doctrine",
		Short: "Legacy doctrine: project-scoped rulings carrying an area; bind only where no AGENTS.md covers the code",
		Long: `Read the legacy doctrine: the active project-scoped rulings that carry an area,
a law and a rationale. A law is identified by its ruling id — there is no code
column and no doctrine table.

Doctrine is legacy, like every ruling: it binds only where no AGENTS.md covers
the code. No law is added, amended or promoted; a rule goes into the AGENTS.md
of the folder it governs. A stale law is retired from the owner's interactive
terminal with ` + "`bd ruling retire`" + `.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			return cmd.Help()
		},
	}
	root.AddCommand(newDoctrineListCmd())
	root.AddCommand(newDoctrineRenderCmd())
	root.AddCommand(newDoctrinePromoteCmd())
	return root
}

func newDoctrineListCmd() *cobra.Command {
	var concern, workspace string
	cmd := &cobra.Command{
		Use:   "list",
		Short: "List the laws: ruling id, area, law",
		Long: `Print one line per law — its ruling id, its area and the law itself.

--concern and --workspace narrow the listing; together they mean AND. Both are
checked against the area vocabulary, so a typo is refused with the vocabulary
rather than silently listing nothing.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			cc, err := openStore(cmd)
			if err != nil {
				return err
			}
			defer cc.store.Close()

			if err := validateAreaName(cc, store.AreaConcern, concern); err != nil {
				return err
			}
			if err := validateAreaName(cc, store.AreaWorkspace, workspace); err != nil {
				return err
			}

			laws, err := cc.store.ListDoctrine(cc.ctx, store.DoctrineFilter{
				Concern:   strings.TrimSpace(concern),
				Workspace: strings.TrimSpace(workspace),
			})
			if err != nil {
				return err
			}
			writeDoctrineTable(cmd.OutOrStdout(), laws)
			return nil
		},
	}
	cmd.Flags().StringVar(&concern, "concern", "", "only laws carrying this concern")
	cmd.Flags().StringVar(&workspace, "workspace", "", "only laws carrying this workspace")
	return cmd
}

func newDoctrineRenderCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "render",
		Short: "Write the whole doctrine page to stdout",
		Long: `Render every law as one markdown page, grouped by area: the concerns in
vocabulary order, then the workspaces. Within a heading each law is bold, its
rationale is the paragraph under it, and an attribution line cites the ruling.

The page is generated, so it is redirected over the file it replaces:

    bd doctrine render > docs/doctrine.md`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			cc, err := openStore(cmd)
			if err != nil {
				return err
			}
			defer cc.store.Close()

			laws, err := cc.store.ListDoctrine(cc.ctx, store.DoctrineFilter{})
			if err != nil {
				return err
			}
			areas, err := cc.store.ListAreas(cc.ctx)
			if err != nil {
				return err
			}
			writeDoctrinePage(cmd.OutOrStdout(), areas, laws)
			return nil
		},
	}
	return cmd
}

